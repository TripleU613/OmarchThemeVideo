"""Audio features the scenes react to, precomputed so renders stay deterministic.

  bands  16 log-spaced spectrum bands of the full mix (like the site's music.ts), 0..255
  vocal  RMS envelope of the isolated vocal stem, 0..255
  kick   low-band onset strength of the instrumental stem, 0..255

All at 60 frames per second, written as base64 into music-video/assets/lib/audio.js.
"""
import base64
import json
from pathlib import Path

import librosa
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
FPS = 60
SR = 48000
HOP = SR // FPS


def norm(x, lo_pct=5, hi_pct=99.5):
    lo, hi = np.percentile(x, lo_pct), np.percentile(x, hi_pct)
    return np.clip((x - lo) / (hi - lo + 1e-9), 0, 1)


def pack(a):
    return base64.b64encode((np.clip(a, 0, 1) * 255).round().astype(np.uint8).tobytes()).decode()


mix, _ = librosa.load(ROOT / "source/song-audio.wav", sr=SR, mono=True)
voc, _ = librosa.load(ROOT / "analysis/stems/htdemucs_ft/song-audio/vocals.wav", sr=SR, mono=True)
inst, _ = librosa.load(ROOT / "analysis/stems/htdemucs_ft/song-audio/no_vocals.wav", sr=SR, mono=True)
n = int(np.ceil(len(mix) / HOP))

S = np.abs(librosa.stft(mix, n_fft=4096, hop_length=HOP, center=True))[:, :n]
freqs = librosa.fft_frequencies(sr=SR, n_fft=4096)
edges = np.geomspace(40, 14000, 17)
bands = np.stack([S[(freqs >= a) & (freqs < b)].mean(0) for a, b in zip(edges[:-1], edges[1:])])
bands = librosa.amplitude_to_db(bands, ref=np.max)
bands = np.stack([norm(b, 20, 99.7) for b in bands]) ** 1.4  # per band, so highs read as well as lows

vocal = librosa.feature.rms(y=voc, frame_length=HOP * 4, hop_length=HOP)[0][:n]
vocal = norm(librosa.amplitude_to_db(vocal, ref=np.max), 30, 99.5)

kick = librosa.onset.onset_strength(y=inst, sr=SR, hop_length=HOP, fmax=160, n_mels=32)[:n]
kick = norm(kick, 50, 99.8)

out = {"fps": FPS, "frames": n, "bands": 16, "spectrum": pack(bands.T.reshape(-1)), "vocal": pack(vocal), "kick": pack(kick)}
dest = ROOT / "music-video/assets/lib/audio.js"
dest.write_text(
    "// Generated by analysis/features.py: 16-band spectrum, vocal envelope and kick strength at 60fps.\n"
    f"window.OM_AUDIO = {json.dumps(out)};\n"
)
print(n, "frames ->", dest, f"{dest.stat().st_size/1e6:.1f} MB")
