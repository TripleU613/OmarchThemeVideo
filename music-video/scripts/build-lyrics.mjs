// Maps the lyrics you paste into lyrics.txt onto the aligned word windows and
// writes assets/lib/lyrics.js for the caption layer.
//
//   node scripts/build-lyrics.mjs               # reads lyrics.txt
//   node scripts/build-lyrics.mjs --placeholder # w1 w2 ... per line, for layout checks
//
// lyrics.txt: one sung line per line, in song order. Blank lines and [Section]
// headers are skipped, the same way analysis/align.py read the sheet. Words are
// counted with align.py's rule (letters and apostrophes; anything else splits),
// so each line must have exactly as many words as it was aligned with. A lone
// "~" stands for a timed word with no text. The report names lines by id and
// counts only; it never prints the text. scripts/lyrics-from-lrc.mjs writes
// lyrics.txt from a word-by-word .lrc/.srt/.ass file.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const LINES = JSON.parse(fs.readFileSync(path.join(ROOT, '../analysis/lines.json'), 'utf8'));
const lines = Array.isArray(LINES) ? LINES : LINES.lines;
const OUT = path.join(ROOT, 'assets/lib/lyrics.js');
const placeholder = process.argv.includes('--placeholder');

/** Display words for one line: a new word starts at each run of letters/apostrophes; other characters stay attached. */
function words(line) {
  const out = [];
  for (const token of line.split(/\s+/).filter(Boolean)) {
    if (token === '~') { out.push({ text: '', space: '' }); continue; } // a timed word with no text
    const parts = token.match(/[^a-z'’]*[a-z'’]+[^a-z'’]*/gi);
    if (!parts) {
      if (out.length) out[out.length - 1].text += ' ' + token; // a token with no letters (an ampersand, a dash) rides on the word before
      continue;
    }
    parts.forEach((text, i) => out.push({ text, space: i === 0 ? ' ' : '' }));
  }
  return out;
}

let sung;
if (placeholder) {
  sung = lines.map((l) => l.words.map((_, i) => ({ text: `w${i + 1}`, space: ' ' })));
} else {
  const file = path.join(ROOT, 'lyrics.txt');
  if (!fs.existsSync(file)) {
    console.error('lyrics.txt not found. Paste the lyrics there: one sung line per line, in order.');
    process.exit(1);
  }
  const raw = fs.readFileSync(file, 'utf8').split(/\r?\n/).map((s) => s.trim()).filter((s) => s && !/^\[.*\]$/.test(s));
  if (raw.length !== lines.length) {
    console.error(`lyrics.txt has ${raw.length} lines; the song was aligned as ${lines.length}. Check for missing, extra or split lines.`);
    process.exit(1);
  }
  sung = raw.map(words);
  const bad = lines.map((l, i) => [l.id, sung[i].length, l.words.length]).filter(([, a, b]) => a !== b);
  if (bad.length) {
    console.error('Word counts differ from the alignment on these lines (id: pasted vs aligned):');
    for (const [id, a, b] of bad) console.error(`  ${id}: ${a} vs ${b}`);
    process.exit(1);
  }
}

const data = Object.fromEntries(lines.map((l, i) => [l.id, sung[i].map((w) => [w.text, w.space])]));
fs.writeFileSync(OUT, `// Generated by scripts/build-lyrics.mjs${placeholder ? ' (placeholder words)' : ' from lyrics.txt'}. Do not edit.\nwindow.OM_LYRICS = ${JSON.stringify(data)};\n`);
console.log(`${placeholder ? 'placeholder ' : ''}lyrics.js written: ${lines.length} lines, ${lines.reduce((n, l) => n + l.words.length, 0)} words, all counts match.`);
