// Builds assets/lib/timing.js from the analysis: lyric line windows (timing
// only), the beat grid, downbeats, and the drums measured on the real song
// (analysis/drums.json, from analysis/refine_events.py). Every scene reads its
// sync points from here, so nothing is timed by hand.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const here = (p) => new URL(p, import.meta.url)
const lines = JSON.parse(readFileSync(here('../../analysis/lines.json'), 'utf8'))
const map = JSON.parse(readFileSync(here('../../analysis/audiomap.json'), 'utf8'))

const beats = map.grid.beats_sec
const phase = map.tempo.downbeat_phase ?? 0
const downbeats = beats.filter((_, i) => (i - phase) % map.tempo.beats_per_bar === 0)
const r3 = (x) => Math.round(x * 1000) / 1000

const out = {
  bpm: map.tempo.bpm,
  duration: map.audio.duration_sec,
  beats: beats.map(r3),
  downbeats: downbeats.map(r3),
  phrases: map.phrases.map((p) => [r3(p.start), r3(p.end)]),
  lines: lines.map((l) => ({
    id: l.id,
    section: l.section,
    start: r3(l.start),
    end: r3(l.end),
    words: l.words.map((w) => (w ? [r3(w[0]), r3(w[1])] : null)),
  })),
}
// The drums as measured on the song: every hit at its attack, every beat at its hit.
if (existsSync(here('../../analysis/drums.json'))) {
  const d = JSON.parse(readFileSync(here('../../analysis/drums.json'), 'utf8'))
  out.beatsOn = d.beats
  out.downbeatsOn = d.beats.filter((_, i) => (i - phase) % map.tempo.beats_per_bar === 0)
  out.drums = { kick: d.kick, snare: d.snare, hat: d.hat, perc: d.perc }
  out.fills = d.fills
  out.risers = d.risers
  out.stops = d.stops
}
writeFileSync(
  here('../assets/lib/timing.js'),
  `// Generated by scripts/build-timing.mjs. Timing only: the words are in lyrics.js.\nwindow.OM_TIMING = ${JSON.stringify(out)};\n`,
)
console.log(`${out.lines.length} lines, ${out.beats.length} beats, ${out.downbeats.length} downbeats, bpm ${out.bpm}` + (out.drums ? `, ${out.drums.kick.length} kicks, ${out.drums.snare.length} snares, ${out.fills.length} fills measured on the song` : ''))
