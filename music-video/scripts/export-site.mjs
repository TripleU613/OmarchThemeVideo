// Export the live player as an /anthem page for a checkout of omarchy-site:
//   node scripts/export-site.mjs ../omarchy-site
// Writes anthem/index.html and assets/anthem/ there, from play.html (run assemble first).
// The page plays the copy of the song that site already ships, and loads three.js
// from the upstream npm files (checksums pinned below) instead of this repo's bundle.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'

const here = (p) => new URL(p, import.meta.url).pathname
const site = resolve(process.argv[2] || '')
if (!process.argv[2]) throw new Error('usage: node scripts/export-site.mjs <omarchy-site checkout>')

// That site's mp3 is this repo's song.wav without its first 0.526 s (measured by
// cross-correlation at six points across the song: constant, no drift).
const SONG = '/music/kevin_koontz-we_can_fix_everything.mp3', OFFSET = 0.526
const FILM = 'https://youtu.be/R91DhtkbYLs', REPO = 'https://github.com/TripleU613/OmarchThemeVideo'
const THREE = {
  version: '0.181.2',
  files: {
    'three.module.min.js': '979c1ae4b0579c9901eacf797602c0b46df129d87102c6443d14be4a1f790b70',
    'three.core.min.js': '295a28f4a9786dd24a2a357a4ce90921eb041127e53a508335b9a0556c1e0875',
  },
}
const git = (...a) => execFileSync('git', a, { cwd: here('..'), encoding: 'utf8' }).trim()
const commit = git('rev-parse', '--short', 'HEAD') + (git('status', '--porcelain', '--', '.') ? '+uncommitted' : '')

const out = join(site, 'assets/anthem')
rmSync(out, { recursive: true, force: true })
rmSync(join(site, 'anthem'), { recursive: true, force: true })
mkdirSync(join(out, 'vendor'), { recursive: true })
mkdirSync(join(site, 'anthem'))

// three.js straight from npm, checked against the pinned checksums.
const tmp = mkdtempSync(join(tmpdir(), 'three-'))
execFileSync('npm', ['pack', `three@${THREE.version}`, '--silent'], { cwd: tmp })
execFileSync('tar', ['-xzf', `three-${THREE.version}.tgz`, 'package/build', 'package/LICENSE'], { cwd: tmp })
for (const [f, sum] of Object.entries(THREE.files)) {
  const data = readFileSync(join(tmp, 'package/build', f))
  if (createHash('sha256').update(data).digest('hex') !== sum) throw new Error(`three ${f}: checksum mismatch`)
  writeFileSync(join(out, 'vendor', f), data)
}
cpSync(join(tmp, 'package/LICENSE'), join(out, 'vendor/LICENSE-three.txt'))
rmSync(tmp, { recursive: true })

// The page: play.html with that site's head, paths and song.
let html = readFileSync(here('../play.html'), 'utf8')
const swap = (from, to) => {
  if (!(from instanceof RegExp ? from.test(html) : html.includes(from))) throw new Error(`export: play.html no longer has ${from}`)
  html = html.replace(from, to)
}
swap(/<meta charset[\s\S]*?<!-- Generated by scripts\/assemble.mjs. -->/, `<title>Anthem — Omarchy</title>

    <meta charset="utf-8">
    <meta name="viewport" content="initial-scale=1, width=device-width">
    <meta name="description" content="We Can Fix Everything, the Omarchy anthem, as a film drawn live in your browser: 66 scenes of JavaScript, no video file.">
    <meta name="theme-color" content="#0e0e14">

    <link rel="canonical" href="https://omarchy.org/anthem">

    <meta property="og:site_name" content="Omarchy">
    <meta property="og:title" content="Anthem">
    <meta property="og:description" content="We Can Fix Everything, the Omarchy anthem, as a film drawn live in your browser.">
    <meta property="og:image" content="https://omarchy.org/assets/images/social/anthem.jpg">
    <meta property="og:image:width" content="1200">
    <meta property="og:image:height" content="630">
    <meta property="og:url" content="https://omarchy.org/anthem">
    <meta property="og:type" content="website">
    <meta name="twitter:card" content="summary_large_image">

    <link rel="icon" href="/assets/images/favicon.png">

    <!-- Exported from ${REPO} at ${commit} by music-video/scripts/export-site.mjs. Edit there, not here. -->`)
swap(/<script src="assets\/vendor\/three\.iife\.min\.js[^"]*"><\/script>/,
  `<script>window.OM_THREE = import('/assets/anthem/vendor/three.module.min.js').then((m) => { window.THREE = m; }); // upstream three ${THREE.version}</script>`)
swap(/data-src="[^"]*"/, `data-src="${SONG}" data-offset="${OFFSET}"`)
swap('<div id="note">', `<noscript><p style="padding: 2rem">This film is drawn live with JavaScript. <a href="${FILM}">Watch the rendered film</a>.</p></noscript>\n    <div id="note">`)
html = html.replaceAll(/(src|href)="assets\/dev\/(play\.(?:js|css))/g, '$1="/assets/anthem/$2').replaceAll(/(src|href)="assets\//g, '$1="/assets/anthem/').replaceAll("url('assets/", "url('/assets/anthem/")
writeFileSync(join(site, 'anthem/index.html'), html)

// Only the files the page loads.
const copied = []
for (const [, p] of html.matchAll(/["'(]\/assets\/anthem\/([^"'?)]+)/g)) {
  if (p.startsWith('vendor/')) continue
  const from = here('../assets/' + (/^play\.(js|css)$/.test(p) ? 'dev/' + p : p))
  mkdirSync(dirname(join(out, p)), { recursive: true })
  cpSync(from, join(out, p))
  copied.push(p)
}
writeFileSync(join(out, 'README.md'), `# Anthem

The film at /anthem: *We Can Fix Everything (The Ultimate Machine)* drawn live in the
browser. Exported from ${REPO} at \`${commit}\` by \`music-video/scripts/export-site.mjs\`;
change it there and export again, not here.

- \`lib/\`, \`scenes/\`, \`play.js\`, \`play.css\`: the film's engine, its 66 scenes and the player. MIT.
- \`lib/lyrics.js\`: the song's words with their timing. They belong to the song's owners, like the song.
- \`vendor/\`: three.js ${THREE.version}, the unmodified npm build. MIT (\`LICENSE-three.txt\`). sha256:
${Object.entries(THREE.files).map(([f, s]) => `  - \`${f}\` ${s}`).join('\n')}
- \`fonts/\`: JetBrains Mono (variable). SIL Open Font License 1.1.

The page plays \`${SONG}\`, which starts ${OFFSET} s into the film's own clock.
`)
console.log(`exported ${copied.length} files + three ${THREE.version} to ${site} (film at ${commit})`)
