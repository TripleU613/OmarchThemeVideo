// Pulls every [data-theme] token block out of the site's stylesheet into
// assets/lib/themes.js, so the video wears the site's exact palettes.
import { readFileSync, writeFileSync } from 'node:fs'

const site = new URL('../../omarchy-site/', import.meta.url)
const css = readFileSync(new URL('src/styles.css', site), 'utf8')
const meta = readFileSync(new URL('src/lib/site-themes.ts', site), 'utf8')
const names = Object.fromEntries(
  [...meta.matchAll(/id: '([^']+)', name: '([^']+)'(, light: true)?/g)].map((m) => [m[1], { name: m[2], light: !!m[3] }]),
)
const themes = {}
for (const [, id, body] of css.matchAll(/\[data-theme='([^']+)'\]\s*\{([^}]*)\}/g)) {
  const tokens = {}
  for (const [, key, value] of body.matchAll(/--t-([a-z0-9-]+):\s*([^;]+);/g)) tokens[key] = value.replace(/\s+/g, ' ').trim()
  themes[id] = { id, ...names[id], ...tokens }
}
const order = Object.keys(names)
const out = `// Generated by scripts/extract-themes.mjs from omarchy-site/src/styles.css. Do not edit.\nwindow.OM_THEMES = ${JSON.stringify(Object.fromEntries(order.map((id) => [id, themes[id]])), null, 1)};\n`
writeFileSync(new URL('../assets/lib/themes.js', import.meta.url), out)
